// Bundles server/handler.ts, with everything it imports, into the single JavaScript file api/ask.js.
// Vercel serves anything in api/ as a function; shipping plain JavaScript means it never has to compile
// TypeScript or resolve imports outside api/, which is where TypeScript functions tend to break.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

export const apiBuildOptions = {
  absWorkingDir: root,
  entryPoints: ['server/handler.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-api.mjs from server/handler.ts. Do not edit; run `npm run build:api`.' },
};

/** The bundle as text, without writing it, so a test can check that the committed file is up to date. */
export async function bundleApi() {
  const result = await build({ ...apiBuildOptions, write: false, outfile: 'api/ask.js' });
  return result.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await build({ ...apiBuildOptions, outfile: 'api/ask.js' });
  console.log('api/ask.js written');
}
